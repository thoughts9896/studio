// Filenames carry a content hash (name-1600.<hash>.webp): a changed screenshot always gets a
// new URL, so no CDN or browser can keep serving an old copy. Hashed files are cached immutably.
const hash = (buf) => crypto.createHash('sha256').update(buf).digest('hex').slice(0, 8)

async function emit(buf, base, widths) {
  const { width } = await sharp(buf).metadata()
  const v = hash(buf)
  for (const w of widths) {
    const img = sharp(buf).resize({ width: Math.min(w, width) })
    await img.clone().avif({ quality: 58, effort: 6 }).toFile(path.join(OUT, `${base}-${w}.${v}.avif`))
    await img.clone().webp({ quality: 82 }).toFile(path.join(OUT, `${base}-${w}.${v}.webp`))
  }
  return v
}

const sizes = {}
for (const [src, name, crop, phone] of shots) {
  const raw = fs.readFileSync(path.join(RAW, src))
  const desk = crop ? await sharp(raw).extract(crop).toBuffer() : raw
  const m = await sharp(desk).metadata()
  sizes[name] = { w: m.width, h: m.height }
  sizes[name].v = await emit(desk, name, [960, 1600, 2400])
  if (phone) {
    const pb = await sharp(raw).extract(phone).toBuffer()
    sizes[name].mw = phone.width
    sizes[name].mh = phone.height
    sizes[name].mv = await emit(pb, `${name}-m`, [800, 1200])
  }
  console.log('ok', name, sizes[name])
}

// The synthetic test bill used for the scan demo (made-up supplier, marked "synthetic test data").
const bill = '/Users/apple/MedDeskData/synthetic-bills/S01-busy-intra.jpg'
if (fs.existsSync(bill)) {
  const buf = fs.readFileSync(bill)
  const v = hash(buf)
  const m = await sharp(buf).resize({ width: 1200 }).toBuffer().then((b) => sharp(b).metadata())
  for (const w of [700, 1200]) {
    await sharp(buf).resize({ width: w }).avif({ quality: 60 }).toFile(path.join(OUT, `bill-${w}.${v}.avif`))
    await sharp(buf).resize({ width: w }).webp({ quality: 80 }).toFile(path.join(OUT, `bill-${w}.${v}.webp`))
  }
  sizes.bill = { w: m.width, h: m.height, v }
  console.log('ok bill')
}

fs.writeFileSync(
  path.resolve('src/shots.gen.ts'),
  `// Generated by scripts/images.mjs. Do not edit.\nexport const SHOTS: Record<string, { w: number; h: number; v: string; mw?: number; mh?: number; mv?: string }> = ${JSON.stringify(sizes, null, 2)}\n`,
)
